/** Screen 6 — specification workspace: functional, NFR, diagrams, data and API models. */
import { useState } from 'react'
import { useParams } from 'react-router-dom'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'

import { api, download } from '../lib/api'
import { useI18n } from '../i18n'
import { AddSpecificationModal } from '../components/entry-forms'
import {
  Badge, EmptyState, ErrorBanner, Note, PageHeader, Section, Spinner, StateBadge, Tabs,
} from '../components/ui'
import type { Specification } from '../types'

const KIND_LABEL: Record<string, string> = {
  functional: 'Functional',
  non_functional: 'Non functional',
  process_diagram: 'Process diagrams',
  data_model: 'Data model',
  api: 'API specification',
  ux: 'UX',
  data: 'Data',
}

export function SpecificationsPage() {
  const { projectId = '' } = useParams()
  const { t } = useI18n()
  const queryClient = useQueryClient()
  const [kind, setKind] = useState('functional')
  const [writing, setWriting] = useState(false)

  const specs = useQuery({
    queryKey: ['specifications', projectId],
    queryFn: () => api<Specification[]>(`/projects/${projectId}/specifications`),
  })
  const create = useMutation({
    mutationFn: (body: Record<string, unknown>) =>
      api(`/projects/${projectId}/specifications`, { method: 'POST', body }),
    onSuccess: (created) => {
      void queryClient.invalidateQueries({ queryKey: ['specifications', projectId] })
      setKind((created as Specification).kind)
      setWriting(false)
    },
  })

  // The screen keeps its heading (and so its document title) while it loads or fails.
  const loadingHeader = <PageHeader title={t('navSpecifications')} />
  if (specs.isLoading) return <>{loadingHeader}<Spinner /></>
  if (specs.error) return <>{loadingHeader}<ErrorBanner error={specs.error} onRetry={specs.refetch} /></>

  const all = specs.data ?? []
  const shown = all.filter((spec) => spec.kind === kind)

  return (
    <>
      <PageHeader
        title={t('navSpecifications')}
        subtitle="Generated specifications are structurally validated proposals, not implemented contracts."
        actions={
          <>
            <button type="button" className="btn-secondary"
                    onClick={() => download(
                      `/projects/${projectId}/exports`, `${projectId}-specifications.md`)
                      .catch(() => undefined)}>
              Export Markdown
            </button>
            <button type="button" className="btn-primary"
                    onClick={() => setWriting(true)}>Write a specification</button>
          </>
        }
      />

      <Tabs active={kind} onChange={setKind}
            tabs={Object.entries(KIND_LABEL).map(([key, label]) => ({
              key, label, count: all.filter((spec) => spec.kind === key).length,
            }))} />

      {shown.length === 0 ? (
        <EmptyState title="No specification of this kind yet"
                    hint="The technical analyst stage produces data models, API proposals and process diagrams; the business analyst produces the functional specification. You can also write one by hand."
                    action={<button type="button" className="btn-primary"
                                    onClick={() => setWriting(true)}>
                      Write a specification
                    </button>} />
      ) : (
        <div className="space-y-4">
          {shown.map((spec) => (
            <Section key={spec.id} title={spec.title}
                     description={spec.generatedByRole
                       ? `Generated by the ${spec.generatedByRole.replace('_', ' ')} · ${spec.modelId}`
                       : undefined}
                     actions={
                       <div className="flex items-center gap-2">
                         <Badge tone="muted">v{spec.version}</Badge>
                         <StateBadge state={spec.state} />
                       </div>
                     }>
              {spec.validation?.note ? (
                <div className="mb-3"><Note tone="muted">{String(spec.validation.note)}</Note></div>
              ) : null}

              {spec.body ? (
                <article className="prose prose-sm max-w-none whitespace-pre-wrap
                                    text-sm leading-relaxed text-ink-800">
                  {spec.body}
                </article>
              ) : null}

              {spec.diagramSource ? (
                <div>
                  <p className="mb-1 text-xs text-ink-500">
                    Mermaid source — render it in any Mermaid viewer or the exported Markdown.
                  </p>
                  <pre className="overflow-x-auto rounded-lg bg-code p-3 text-xs
                                  text-code-text">{spec.diagramSource}</pre>
                </div>
              ) : null}

              {spec.structured && Object.keys(spec.structured).length ? (
                <details className="mt-2">
                  <summary className="cursor-pointer text-xs font-medium text-brand-700">
                    Structured content
                  </summary>
                  <pre className="mt-2 max-h-96 overflow-auto rounded-lg bg-ink-50 p-3
                                  text-xs">{JSON.stringify(spec.structured, null, 2)}</pre>
                </details>
              ) : null}
            </Section>
          ))}
        </div>
      )}

      <AddSpecificationModal open={writing} onClose={() => setWriting(false)}
                             onCreate={(body) => create.mutate(body)}
                             busy={create.isPending} error={create.error} />
    </>
  )
}
